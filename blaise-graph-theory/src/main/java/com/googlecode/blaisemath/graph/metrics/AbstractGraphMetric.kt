 * @param <T> computed value type
 * @author Elisha Peterson
</T> */
abstract class AbstractGraphMetric<T>(private val name: String?, private val description: String?, private val supportsDirected: Boolean) : GraphMetric<T?> {
    override fun toString(): String {
        return name
    }

    fun getName(): String? {
        return name
    }

    fun getDescription(): String? {
        return description
    }

    fun supportsGraph(directed: Boolean): Boolean {
        return !directed || supportsDirected
    }
}